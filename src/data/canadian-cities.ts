import CANADIAN_SETTLEMENTS_RAW from './canadian-settlements.json';

const PROV_SLUG_TO_CODE: Record<string, string> = {
  ontario: 'on',
  quebec: 'qc',
  'british-columbia': 'bc',
  alberta: 'ab',
  manitoba: 'mb',
  saskatchewan: 'sk',
  'nova-scotia': 'ns',
  'new-brunswick': 'nb',
  newfoundland: 'nl',
  'newfoundland-and-labrador': 'nl',
  'prince-edward-island': 'pe',
  pei: 'pe',
  yukon: 'yt',
  'northwest-territories': 'nt',
  nwt: 'nt',
  nunavut: 'nu',
};

// In-memory O(1) settlement lookup index
const settlementsMap = new Map<string, CanadianCity>();

function indexCity(city: CanadianCity) {
  const pCode = city.provinceCode.toLowerCase();
  const cSlug = city.slug.toLowerCase();
  settlementsMap.set(`${pCode}:${cSlug}`, city);

  // Also map full province slug
  for (const [provSlug, code] of Object.entries(PROV_SLUG_TO_CODE)) {
    if (code === pCode) {
      settlementsMap.set(`${provSlug}:${cSlug}`, city);
    }
  }
}

for (const city of CANADIAN_CITIES) {
  indexCity(city);
}

for (const s of CANADIAN_SETTLEMENTS_RAW) {
  const key = `${s.provinceCode.toLowerCase()}:${s.slug.toLowerCase()}`;
  if (!settlementsMap.has(key)) {
    indexCity(s as CanadianCity);
  }
}

export const ALL_CANADIAN_SETTLEMENTS: CanadianCity[] = Array.from(
  new Set(settlementsMap.values())
);

// Helper Functions
export function getCityBySlug(provinceSlugOrCode: string, citySlug: string): CanadianCity | undefined {
  if (!provinceSlugOrCode || !citySlug) return undefined;
  const normProvince = provinceSlugOrCode.toLowerCase();
  const normCity = citySlug.toLowerCase();

  const key = `${normProvince}:${normCity}`;
  const directMatch = settlementsMap.get(key);
  if (directMatch) return directMatch;

  const resolvedCode = PROV_SLUG_TO_CODE[normProvince] || normProvince.slice(0, 2);
  return settlementsMap.get(`${resolvedCode}:${normCity}`);
}

export function getCitiesByProvince(provinceCode: string): CanadianCity[] {
  const pCode = provinceCode.toUpperCase();
  return CANADIAN_CITIES.filter(
    (c) => c.provinceCode.toUpperCase() === pCode
  ).sort((a, b) => b.population - a.population);
}

export function getAllSettlementsByProvince(provinceCode: string): CanadianCity[] {
  const pCode = provinceCode.toUpperCase();
  return ALL_CANADIAN_SETTLEMENTS.filter(
    (c) => c.provinceCode.toUpperCase() === pCode
  ).sort((a, b) => b.population - a.population);
}

export function searchCanadianCities(query: string, limit = 12): CanadianCity[] {
  if (!query || query.trim().length < 1) return [];
  const q = query.trim().toLowerCase();

  const results: CanadianCity[] = [];
  const addedSlugs = new Set<string>();

  // 1. Search primary cities first (highest relevance)
  for (const city of CANADIAN_CITIES) {
    const nameMatch = city.name.toLowerCase().includes(q);
    const nameFrMatch = city.nameFr?.toLowerCase().includes(q);
    const slugMatch = city.slug.toLowerCase().includes(q);
    const provMatch = city.provinceCode.toLowerCase() === q;
    const fsaMatch = city.postalCodePrefix?.some((fsa) => fsa.toLowerCase().startsWith(q));

    if (nameMatch || nameFrMatch || slugMatch || provMatch || fsaMatch) {
      results.push(city);
      addedSlugs.add(`${city.provinceCode}:${city.slug}`);
      if (results.length >= limit) break;
    }
  }

  // 2. If needed, supplement with deep settlements
  if (results.length < limit) {
    for (const s of ALL_CANADIAN_SETTLEMENTS) {
      const key = `${s.provinceCode}:${s.slug}`;
      if (addedSlugs.has(key)) continue;

      if (
        s.name.toLowerCase().includes(q) ||
        s.slug.toLowerCase().includes(q) ||
        s.postalCodePrefix?.some((fsa) => fsa.toLowerCase().startsWith(q))
      ) {
        results.push(s);
        addedSlugs.add(key);
        if (results.length >= limit) break;
      }
    }
  }

  return results.slice(0, limit);
}

export function getFeaturedCanadianCities(): CanadianCity[] {
  return CANADIAN_CITIES.filter((c) => c.featured).sort((a, b) => b.population - a.population);
}
