export const PROVINCE_LIST = Object.values(CANADIAN_PROVINCES);

const PROVINCE_MAP_BY_SLUG = new Map<string, Province>();
for (const p of PROVINCE_LIST) {
  PROVINCE_MAP_BY_SLUG.set(p.slug.toLowerCase(), p);
  PROVINCE_MAP_BY_SLUG.set(p.code.toLowerCase(), p);
}

export function getProvinceByCode(code: string): Province | undefined {
  if (!code) return undefined;
  return CANADIAN_PROVINCES[code.toUpperCase()];
}

export function getProvinceBySlug(slug: string): Province | undefined {
  if (!slug) return undefined;
  return PROVINCE_MAP_BY_SLUG.get(slug.toLowerCase());
}
